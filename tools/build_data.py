"""Build data/implants.csv and data/implants.js from the transcribed source tables."""
import csv, json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from allergan_source import PROFILES

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIELDS = ["manufacturer", "line", "catalog", "gel", "profile", "shape", "surface",
          "volume_cc", "diameter_cm", "projection_cm"]

rows = []
for _, (label, prefixes, data) in PROFILES.items():
    for gel, prefix in prefixes.items():
        for vol, dia, proj in data:
            rows.append(dict(manufacturer="Allergan", line="Natrelle INSPIRA",
                             catalog=f"{prefix}-{vol}", gel=gel, profile=label,
                             shape="Round", surface="Smooth", volume_cc=vol,
                             diameter_cm=dia, projection_cm=proj))

with open(ROOT / "data/implants.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=FIELDS); w.writeheader(); w.writerows(rows)
(ROOT / "data/implants.js").write_text(
    "// Generated by tools/build_data.py - do not edit by hand.\n"
    "window.IMPLANTS = " + json.dumps(rows, indent=1) + ";\n")
print(len(rows), "implants written")
